"""``math_foundations`` 的失败族：**数学层会怎么失败，每一种该谁去修**（day073）.

分族的依据与 ``rag_ops.errors`` / ``rag_debug.errors`` 逐字相同——
**按"谁的错、该谁去修"分**，而不是按"哪一行抛的"：

```text
ShapeError      形状不符      维度不一致、不是方阵、行列数对不上   → 改调用
NumericError    数值不可用    非有限数、零向量、负概率、和不为 1   → 改数据或改调用
ParameterError  参数越界      温度 <= 0、秩 <= 0、容差为负、k 越界  → 改调用
TableError      概率表不合法  事件名重复、边缘分布对不上、空表      → 改数据
MathError       本族基类：其余"这一层自己的拒绝"
```

四族都继承 ``ValueError``（与 ``RetrievalError`` / ``RagOpsError`` 同一句话）：
参数写错是**调用方**的问题，因此调用方"参数一律 400"的通道不必为这一族加分支。

## 为什么 ShapeError 与 NumericError 必须分开

它们是这一课最容易混为一谈的两类失败，而处置动作完全不同：

```text
ShapeError    形状不对 → 这个式子**根本没有定义**（3 维向量点 4 维向量）
              处置：改调用——补零、截断或取错子矩阵，都是调用方要决定的事
NumericError  形状对、数值不对 → 式子的定义成立，但**算出来没有意义**
              （零向量没有方向、概率不能是负数、分布必须归一）
              处置：改数据——零向量通常是上游的编码器坏了
```

把两者合成一个 ``MathError`` 之后，报告里只会剩下一句"计算失败"——
而"这个式子没定义"与"这批数据是脏的"是两个人在两个时间点要做的事。

## 一条贯穿全包的纪律：**不替调用方猜**

零向量是这一课最典型的例子。同一个零向量，本包与项目里已有的三处实现
给出了**三种**不同的处理：

```text
vectorstore.metrics.cosine_similarity   返回 0.0（一条脏数据不要打断整批查询）
llm.embedding.l2_normalize              原样返回（避免除零，调用方自己看着办）
math_foundations.linalg.normalize       **报错**（零向量没有方向，这不是它能替调用方决定的事）
```

三种都不是"错"，但它们必须**各自说清自己为什么这样选**——
而"三处悄悄不一样"才是真正危险的那种分歧（见 ``bridge`` 模块的对照表）。
"""

from __future__ import annotations


class MathError(ValueError):
    """``math_foundations`` 这一族错误的基类（判据与 ``RagOpsError`` 同源）."""


class ShapeError(MathError):
    """形状不符：维度不一致、不是方阵、行列数对不上、空向量／空矩阵.

    出路是**改调用**：形状不对时那个式子根本没有定义，
    而"补零还是截断"是调用方要做的决定，不是数学层能替它拍的。
    """


class NumericError(MathError):
    """数值不可用：非有限数、零向量、负的概率、和不唯一的分布.

    出路是**改数据**：形状是对的、式子是有定义的，但算出来的东西没有意义。
    零向量几乎总是上游的编码器坏了（day041 的 ``embedding`` 会把它拦在写入侧）。
    """


class ParameterError(MathError):
    """参数越界：温度 <= 0、秩 < 1、容差为负、``k`` 越界、最大迭代次数 <= 0.

    出路是**改调用**。这类参数不是"运行期数据"，它们是被写进调用点的一次决定——
    因此本包不接受"参数不合法就取个默认值"这种兜底：
    一次被静默替换成默认值的温度，会让"我调了温度"这件事变成假的。
    """


class TableError(MathError):
    """概率表不合法：事件名重复、边缘分布与联合分布对不上、空表.

    出路是**改数据**（改那张表），而不是改代码：
    一张合不拢的联合分布表算出来的条件概率与贝叶斯后验全是错的，
    而它们看起来仍然是"一组和为 1 的数"。
    """


__all__ = [
    "MathError",
    "NumericError",
    "ParameterError",
    "ShapeError",
    "TableError",
]
