"""索引构建会怎么失败（M6-D4）.

day064 的失败族分成"环境 / 数据 / 调用 / 查询"四族，**修复人各不相同**。
今天这一层的失败族结构完全一样，但换成了"建索引"这件事上的四种人：

```text
EncodingError    编码器问题：维度不符 / 空文本 / 提供方拒绝
                 → 换提供方或修文本（不是改库）
ManifestError    清单与库不一致：清单说有、库里没有（或反之）
                 → **这是脏状态**，要么重建要么按清单修库（不是改参数）
VersionError     版本操作非法：回滚到不存在的版本 / 血缘断裂 / 重复登记
                 → 改调用顺序（不是改数据）
BackupError      备份与恢复失败：磁盘不可写 / 快照版本不匹配 / 目录不存在
                 → 修环境（不是改数据）
```

## 为什么"清单与库不一致"必须单独一族

这四族里只有 `ManifestError` 是**本课独有的新问题**，值得多说一句。

day064 的库里"有什么"完全由库自己说了算。今天多了一份**清单**
（manifest）——它记录了"上一版索引是由哪些块、用哪个编码器的哪个版本建成的"。
于是"库里有什么"与"清单说有什么"变成了**两个可以互相矛盾的事实**：

```text
清单里有、库里没有   → 上一次构建半途失败，或有人手工删过记录
库里有、清单里没有   → 有人绕过索引流程直接写了库
两者的向量维度不同    → 清单是用另一个编码器写的（换过提供方但没重建）
```

这三种状态**都不会在检索时抛异常**——它们只会让"增量更新"算出错误的差集，
于是本该重算的块被判定为"没变"。**错的是差集，症状是检索质量下降**，
而这两者之间隔了好几步。所以这一族异常的存在意义是：
把"清单与库对不上的那一刻"变成一个当场就能看见的事件
（`manifest.compare_with_store` 与 `builder.verify` 是它的两个检查点）。
"""

from __future__ import annotations


class IndexingError(ValueError):
    """索引构建过程中的业务错误（本包所有异常的基类）.

    继承 ``ValueError`` 而不是 ``Exception``，与 day062 的 ``ChunkingError``
    保持一致：这一层的错误几乎全部来自**配置与数据之间的矛盾**，
    而 ``ValueError`` 正是 Python 里表达"你给的值不成立"的标准类型。
    实际好处是调用方已经写好的 ``except (ChunkingError, ValueError)``
    一行就能兜住它。
    """


class EncodingError(IndexingError):
    """编码失败：维度不符、文本为空、提供方拒绝.

    这一族指向**编码器**，而不是库。最常见的两种触发：

    ```text
    维度不符  提供方返回 768 维，而清单里记的是 384 维
              → 换过模型但没重建索引（**必须先重建，不能混着写**）
    空文本    空白文本在多数提供方那里会得到零向量
              → 零向量没有方向，余弦相似度对它是 0/0
    ```

    注意"维度不符"与 day064 `VectorError` 的区别：那里是"记录与库的维度对不上"，
    这里是"编码器与清单里记的身份对不上"。**前者是库的问题，后者是配置的问题**，
    所以分两个类型、给两条不同的修复建议。
    """


class ManifestError(IndexingError):
    """清单不合法，或清单与实际索引对不上.

    见模块 docstring：这一族是本课独有的新问题，也**最安静**——
    它不会让检索报错，只会让增量更新算错差集。
    """


class VersionError(IndexingError):
    """版本操作非法：回滚到不存在的版本、血缘断裂、版本号重复登记.

    与 day058 的模型版本管理同构：**没有血缘的版本表等于没有版本表**，
    因为"回滚到上一版"这句话里的"上一版"必须有一个确定的答案。
    """


class BackupError(IndexingError):
    """备份或恢复失败：磁盘不可写、快照版本不匹配、目录不存在.

    恢复时的"快照版本不匹配"必须**报错而不是尽力而为**：
    一个用旧格式的快照被读进来一半，得到的是一个"看起来有数据"的库，
    而它的字段含义可能与当前代码不一致。
    """


__all__ = [
    "BackupError",
    "EncodingError",
    "IndexingError",
    "ManifestError",
    "VersionError",
]
